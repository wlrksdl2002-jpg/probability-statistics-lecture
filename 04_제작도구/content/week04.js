// 동전 3개를 차례로 던지는 수형도
function coinTree(depth, seq) {
  return ["앞", "뒤"].map((s) => {
    const word = seq + s;
    return depth === 2 ? { label: s, result: word } : { label: s, children: coinTree(depth + 1, word) };
  });
}

