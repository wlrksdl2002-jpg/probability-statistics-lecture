// 봉지 3개에서 사과(a 초록, b 빨강)를 하나씩 꺼내는 수형도
function appleTree(depth, picked) {
  if (depth === 3) return undefined;
  return ["a", "b"].map((ch) => {
    const word = picked + ch;
    const node = { label: ch };
    if (depth === 2) {
      const na = [...word].filter((c) => c === "a").length;
      const nb = 3 - na;
      const pa = na === 0 ? "" : na === 1 ? "a" : `a^{${na}}`;
      const pb = nb === 0 ? "" : nb === 1 ? "b" : `b^{${nb}}`;
      node.result = pa + pb;
    } else {
      node.children = appleTree(depth + 1, word);
    }
    return node;
  });
}

